import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSchema, isAbstractType } from 'graphql';

const workspaceDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);
const schemaFile = path.join(workspaceDir, 'schema.shopana.graphql');
const outputFile = path.join(
  workspaceDir,
  'packages/shopana-storefront-sdk/src/graphql/apollo/generated/possibleTypes.ts'
);

// Apollo matches fragments on interfaces and unions (`... on Media`) only with possibleTypes.
const schema = buildSchema(await readFile(schemaFile, 'utf8'));
const possibleTypes = Object.fromEntries(
  Object.values(schema.getTypeMap())
    .filter((type) => !type.name.startsWith('__') && isAbstractType(type))
    .map((type) => [
      type.name,
      schema
        .getPossibleTypes(type)
        .map(({ name }) => name)
        .sort(),
    ])
    .sort(([left], [right]) => left.localeCompare(right))
);

await writeFile(
  outputFile,
  `// Generated by scripts/codegen-possible-types.mjs from schema.shopana.graphql. Do not edit.\n` +
    `export const possibleTypes: Record<string, readonly string[]> = ${JSON.stringify(possibleTypes, null, 2)};\n`
);
